    /// 真实 git（临时的全局配置文件）：写入、重复运行替换而不重复、保留用户自己的 insteadOf、卸载只移除我们写入的。
    #[test]
    fn git_config_is_replaced_not_duplicated() {
        if !have("git") {
            return;
        }
        let d = tempfile::tempdir().unwrap();
        let cfg = d.path().join("gitconfig");
        std::fs::write(&cfg, "[url \"git@github.com:\"]\n\tinsteadOf = gh:\n").unwrap();
        let run = |p: &str, a: &[&str]| {
            let o = Command::new(p)
                .args(a)
                .env("GIT_CONFIG_GLOBAL", &cfg)
                .env("GIT_CONFIG_NOSYSTEM", "1")
                .output()
                .map_err(|e| e.to_string())?;
            if o.status.success() {
                Ok(String::from_utf8_lossy(&o.stdout).into_owned())
            } else {
                Err(String::from_utf8_lossy(&o.stderr).into_owned())
            }
        };
        let t1 = &"a1".repeat(16);
        let hosts = vec!["github.com".to_string(), "git.example.com:8121".to_string()];
        configure_git(&run, &format!("http://127.0.0.1:7878/{t1}/https"), &hosts).unwrap();
        configure_git(&run, &format!("http://127.0.0.1:7878/{t1}/https"), &hosts).unwrap();
        // 端口或令牌变化：旧的行被替换。
        let t2 = &"f2".repeat(16);
        configure_git(&run, &format!("http://127.0.0.1:7979/{t2}/https"), &hosts).unwrap();
        let text = std::fs::read_to_string(&cfg).unwrap();
        assert_eq!(text.matches("insteadOf = https://github.com/").count(), 1, "{text}");
        assert_eq!(text.matches("insteadOf = https://git.example.com:8121/").count(), 1, "{text}");
        assert!(!text.contains(t1) && text.contains(&format!("http://127.0.0.1:7979/{t2}/https/github.com/")), "{text}");
        assert!(text.contains("insteadOf = gh:"), "用户自己的配置保留");
        let o = Command::new("git")
            .args(["ls-remote", "--get-url", "https://github.com/o/r.git"])
            .env("GIT_CONFIG_GLOBAL", &cfg)
            .output()
            .unwrap();
        assert_eq!(String::from_utf8_lossy(&o.stdout).trim(), format!("http://127.0.0.1:7979/{t2}/https/github.com/o/r.git"));
        // 没有 git 主机：移除我们写入的全部。
        configure_git(&run, &format!("http://127.0.0.1:7979/{t2}/https"), &hosts[..1]).unwrap();
        assert!(!std::fs::read_to_string(&cfg).unwrap().contains("git.example.com"));
        assert_eq!(remove_git_config(&run), 1);
        let text = std::fs::read_to_string(&cfg).unwrap();
        assert!(!text.contains("127.0.0.1") && text.contains("insteadOf = gh:"), "{text}");
    }
