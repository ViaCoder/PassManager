    /// 替身：记录调用，按前缀返回失败。
    struct Fake {
        calls: RefCell<Vec<String>>,
        fail: Vec<&'static str>,
    }

    impl Fake {
        fn new(fail: &[&'static str]) -> Self {
            Self { calls: RefCell::new(vec![]), fail: fail.to_vec() }
        }
        fn run(&self, prog: &str, args: &[&str]) -> Result<String, String> {
            let line = format!("{prog} {}", args.join(" "));
            self.calls.borrow_mut().push(line.clone());
            if self.fail.iter().any(|f| line.starts_with(f)) { Err(format!("{prog}: denied")) } else { Ok(String::new()) }
        }
    }

    fn ctx<'a>(m: Manager, home: &Path, run: Run<'a>) -> Ctx<'a> {
        Ctx {
            manager: m,
            home: home.to_path_buf(),
            bin: "/opt/pm/PassManager".into(),
            listen: "127.0.0.1:7878".into(),
            config_dir_env: None,
            user: Some("pm-test-user".into()),
            uid: Some(501),
            linger_dir: home.join("linger"),
            run,
        }
    }

    #[test]
    fn systemd_install_is_idempotent_and_tries_linger() {
        let d = tempfile::tempdir().unwrap();
        let fake = Fake::new(&["loginctl"]);
        let run = |p: &str, a: &[&str]| fake.run(p, a);
        let c = ctx(Manager::Systemd, d.path(), &run);
        for _ in 0..2 {
            let (msgs, running) = install_service(&c);
            let msgs = msgs.join("\n");
            assert!(running && msgs.contains("已启用并启动") && msgs.contains("sudo loginctl enable-linger pm-test-user"), "{msgs}");
        }
        let unit = d.path().join(".config/systemd/user").join(UNIT);
        assert_eq!(std::fs::read_to_string(&unit).unwrap(), systemd_unit(Path::new("/opt/pm/PassManager"), "127.0.0.1:7878", None));
        let calls = fake.calls.borrow().clone();
        assert_eq!(
            calls[..4],
            [
                "systemctl --user daemon-reload".to_string(),
                format!("systemctl --user enable {UNIT}"),
                format!("systemctl --user restart {UNIT}"),
                "loginctl --no-ask-password enable-linger".to_string()
            ]
        );
        assert_eq!(calls.len(), 8, "第二次运行同样的调用：{calls:?}");
        // 已启用 linger：不再调用 loginctl。
        std::fs::create_dir_all(d.path().join("linger")).unwrap();
        std::fs::write(d.path().join("linger/pm-test-user"), "").unwrap();
        fake.calls.borrow_mut().clear();
        assert!(install_service(&c).0.join("\n").contains("linger 已启用"));
        assert!(!fake.calls.borrow().iter().any(|l| l.starts_with("loginctl")));
        // 卸载：停止、删除单元。
        fake.calls.borrow_mut().clear();
        assert!(uninstall_service(&c).join("").contains("已停止并移除"));
        assert!(!unit.exists());
        assert_eq!(fake.calls.borrow()[0], format!("systemctl --user disable --now {UNIT}"));
        assert!(uninstall_service(&c).is_empty(), "没有安装时什么都不做");
    }

