//! 一键接入：`/a/<注册码>` 返回为该注册码生成的 POSIX sh 安装脚本，`/a/<注册码>/bin/<目标>` 返回对应平台的 Agent 程序。
//! 脚本安装客户端后运行 `PassManager enroll`：注册、MCP 配置、使用规则，以及 git 凭据代理的用户服务与 insteadOf。
//!
//! - 程序只来自服务器上配置的目录（安装时从发布包复制），请求时从不联网下载；
//! - 脚本内嵌每个可用程序的 SHA-256，下载后校验，不一致时什么都不安装；
//! - 获取脚本或程序**不消耗**注册码，只有 `enroll` 消耗；未知或过期的注册码一律 404，不说明原因；
//! - 只接受 GET / HEAD；按来源限速并审计（经服务端日志）；连接层仍只接受配置的局域网网段。

use std::collections::HashMap;
use std::path::{Path, PathBuf};
use std::sync::Mutex;
use std::time::SystemTime;

/// 支持的 Agent 程序（文件名为 `PassManager-<目标>`）。
pub const TARGETS: &[&str] =
    &["x86_64-unknown-linux-gnu", "aarch64-unknown-linux-gnu", "universal-apple-darwin", "aarch64-apple-darwin", "x86_64-apple-darwin"];
/// 单个程序的大小上限。
const MAX_BIN: u64 = 256 << 20;

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct AgentBin {
    pub target: String,
    pub path: PathBuf,
    pub sha256: String,
    pub size: u64,
}

/// 程序目录的 SHA-256 缓存（按路径、大小与修改时间）。
#[derive(Default)]
pub struct BinCache {
    m: Mutex<HashMap<PathBuf, (u64, SystemTime, String)>>,
}

impl BinCache {
    /// 列出目录中可用的程序（只认 [`TARGETS`] 中的普通文件，不跟随符号链接）。
    pub fn scan(&self, dir: &Path) -> Vec<AgentBin> {
        let mut out = Vec::new();
        for t in TARGETS {
            let p = dir.join(format!("PassManager-{t}"));
            let Ok(md) = std::fs::symlink_metadata(&p) else { continue };
            if !md.file_type().is_file() || md.len() == 0 || md.len() > MAX_BIN {
                continue;
            }
            let mtime = md.modified().unwrap_or(SystemTime::UNIX_EPOCH);
            let cached = self.m.lock().unwrap().get(&p).filter(|(l, m, _)| *l == md.len() && *m == mtime).map(|c| c.2.clone());
            let sha = match cached {
                Some(s) => s,
                None => {
                    let Ok(data) = std::fs::read(&p) else { continue };
                    let s = hex::encode(pm_crypto::sha256(&data));
                    self.m.lock().unwrap().insert(p.clone(), (md.len(), mtime, s.clone()));
                    s
                }
            };
            out.push(AgentBin { target: t.to_string(), path: p, sha256: sha, size: md.len() });
        }
        out
    }
}

/// 注册码的格式（base64url，43 个字符）。不符合的直接 404，不查询服务。
pub fn code_ok(code: &str) -> bool {
    code.len() == 43 && code.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
}

fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

/// 生成安装脚本。`base` 是 `https://域名[:端口]/a/<注册码>`。
pub fn sh_script(base: &str, enroll_url: &str, bins: &[AgentBin]) -> String {
    let mut sums = String::new();
    for b in bins {
        sums.push_str(&format!("      {}) sum={} ;;\n", b.target, b.sha256));
    }
    format!(
        r#"#!/bin/sh
# PassManager agent bootstrap, generated by the PassManager server for one enrollment code.
# The code is valid for 10 minutes and works once; this script contains no other secret.
# It installs the PassManager client to ~/.local/bin (SHA-256 verified), enrolls it with the server,
# configures the MCP server for detected agents, adds the usage rules to their instruction files and
# sets up git over HTTPS (git-proxy user service + insteadOf lines; the server adds the tokens).
set -eu

PM_BASE={base}
PM_ENROLL={enroll}

die() {{
  printf 'PassManager: %s\n' "$*" >&2
  exit 1
}}

main() {{
  os=$(uname -s)
  arch=$(uname -m)
  case "$arch" in
    x86_64 | amd64) arch=x86_64 ;;
    aarch64 | arm64) arch=aarch64 ;;
    *) die "unsupported CPU architecture: $arch" ;;
  esac
  case "$os" in
    Linux) candidates="$arch-unknown-linux-gnu" ;;
    Darwin) candidates="$arch-apple-darwin universal-apple-darwin" ;;
    *) die "unsupported operating system: $os" ;;
  esac
  target=""
  sum=""
  for c in $candidates; do
    case "$c" in
{sums}      *) sum="" ;;
    esac
    if [ -n "$sum" ]; then
      target=$c
      break
    fi
  done
  [ -n "$target" ] || die "the server has no client binary for $os/$arch; use step 2 of the setup text (release package from GitHub, or the pinned source)"
  command -v curl > /dev/null 2>&1 || die "curl is required"
  [ -n "${{HOME:-}}" ] || die "HOME is not set"
  dir="$HOME/.local/bin"
  tmp=$(mktemp -d 2> /dev/null || mktemp -d -t passmanager)
  trap 'rm -rf "$tmp"' EXIT INT TERM
  curl --proto '=https' --tlsv1.3 -fsS -o "$tmp/PassManager" "$PM_BASE/bin/$target" || die "download failed"
  if command -v sha256sum > /dev/null 2>&1; then
    got=$(sha256sum "$tmp/PassManager" | cut -d ' ' -f 1)
  elif command -v shasum > /dev/null 2>&1; then
    got=$(shasum -a 256 "$tmp/PassManager" | cut -d ' ' -f 1)
  else
    die "sha256sum or shasum is required"
  fi
  [ "$got" = "$sum" ] || die "SHA-256 mismatch for the downloaded client; nothing was installed"
  mkdir -p "$dir"
  chmod 0755 "$tmp/PassManager"
  cp "$tmp/PassManager" "$dir/.PassManager.new"
  mv -f "$dir/.PassManager.new" "$dir/PassManager"
  ln -sf PassManager "$dir/passmanager"
  printf 'PassManager: installed %s (%s)\n' "$dir/PassManager" "$target"
  "$dir/PassManager" enroll "$PM_ENROLL" < /dev/null || die "enrollment failed"
  case ":$PATH:" in
    *":$dir:"*) ;;
    *) printf 'PassManager: add %s to PATH to use the passmanager command\n' "$dir" ;;
  esac
}}

main "$@"
"#,
        base = sh_quote(base),
        enroll = sh_quote(enroll_url),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn scan_only_known_regular_files() {
        let d = std::env::temp_dir().join(format!("pm-bins-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(&d).unwrap();
        std::fs::write(d.join("PassManager-x86_64-unknown-linux-gnu"), b"linux-bin").unwrap();
        std::fs::write(d.join("PassManager-universal-apple-darwin"), b"mac-bin").unwrap();
        std::fs::write(d.join("PassManager-evil"), b"x").unwrap();
        std::fs::write(d.join("PassManager-aarch64-unknown-linux-gnu"), b"").unwrap();
        #[cfg(unix)]
        std::os::unix::fs::symlink("/etc/passwd", d.join("PassManager-aarch64-apple-darwin")).unwrap();
        let c = BinCache::default();
        let bins = c.scan(&d);
        let names: Vec<&str> = bins.iter().map(|b| b.target.as_str()).collect();
        assert_eq!(names, vec!["x86_64-unknown-linux-gnu", "universal-apple-darwin"]);
        assert_eq!(bins[0].sha256, hex::encode(pm_crypto::sha256(b"linux-bin")));
        // 内容变化后重新计算。
        std::fs::write(d.join("PassManager-x86_64-unknown-linux-gnu"), b"linux-bin-v2").unwrap();
        assert_eq!(c.scan(&d)[0].sha256, hex::encode(pm_crypto::sha256(b"linux-bin-v2")));
        assert!(c.scan(&d.join("missing")).is_empty());
        let _ = std::fs::remove_dir_all(&d);
    }

    #[test]
    fn script_embeds_sums_and_quotes() {
        let bins = vec![AgentBin { target: "x86_64-unknown-linux-gnu".into(), path: "/x".into(), sha256: "ab".repeat(32), size: 1 }];
        let s = sh_script("https://pm.example.com/a/CODE", "pm-enroll://pm.example.com:8443/CODE#FPR", &bins);
        assert!(s.starts_with("#!/bin/sh\n"));
        assert!(s.contains("PM_BASE='https://pm.example.com/a/CODE'"));
        assert!(s.contains("PM_ENROLL='pm-enroll://pm.example.com:8443/CODE#FPR'"));
        assert!(s.contains(&format!("x86_64-unknown-linux-gnu) sum={} ;;", "ab".repeat(32))));
        assert!(!s.contains("universal-apple-darwin) sum="), "只列出服务器上有的程序");
        assert!(s.trim_end().ends_with("main \"$@\""), "整个脚本读完后才执行（curl | sh）");
        assert!(sh_quote("a'b") == "'a'\\''b'");
        assert!(code_ok(&"A".repeat(43)) && !code_ok(&"A".repeat(42)) && !code_ok(&format!("{}/", "A".repeat(42))));
        assert!(s.contains("\"$dir/PassManager\" enroll \"$PM_ENROLL\""), "注册（含 git 代理服务）由 enroll 完成");
    }

    /// 生成的脚本通过 shellcheck（已安装时）与 `sh -n`。
    #[test]
    fn script_passes_shellcheck() {
        let bins = vec![
            AgentBin { target: "x86_64-unknown-linux-gnu".into(), path: "/x".into(), sha256: "ab".repeat(32), size: 1 },
            AgentBin { target: "universal-apple-darwin".into(), path: "/y".into(), sha256: "cd".repeat(32), size: 1 },
        ];
        let s = sh_script("https://pm.example.com:8121/a/CODE", "pm-enroll://pm.example.com:8121/CODE#FPR", &bins);
        let d = std::env::temp_dir().join(format!("pm-boot-sc-{}", std::process::id()));
        std::fs::create_dir_all(&d).unwrap();
        let f = d.join("bootstrap.sh");
        std::fs::write(&f, &s).unwrap();
        let have =
            |c: &str| std::process::Command::new("sh").args(["-c", &format!("command -v {c}")]).output().is_ok_and(|o| o.status.success());
        if have("sh") {
            let o = std::process::Command::new("sh").arg("-n").arg(&f).output().unwrap();
            assert!(o.status.success(), "{}", String::from_utf8_lossy(&o.stderr));
        }
        if have("shellcheck") {
            let o = std::process::Command::new("shellcheck").args(["-s", "sh"]).arg(&f).output().unwrap();
            assert!(o.status.success(), "{}", String::from_utf8_lossy(&o.stdout));
        }
        let _ = std::fs::remove_dir_all(&d);
    }
}
